"""Result tables for the paper, generated from results/analysis.json only (no sealed access).

Written after the single unseal: analyze.py's docstring promised paper/tables/*.tex but analyze.py writes only
results/analysis.json, so the tables are produced here, mechanically, from that file. Rerunnable (derived files).
Writes paper/tables/{confirmatory,arms_encoder,arms_lm,extensions}.tex. Usage: tables_results.py [ROOT]
"""
import json
import os
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "paper", "tables")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def f(x, nd=3, sign=True):
    if x is None:
        return "--"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$")


def p(x):
    if x is None:
        return "--"
    return "0.002" if abs(x - 0.001953125) < 1e-9 else f"{x:.3f}"


def ci(c, nd=3):
    return f"[{f(c[0], nd)}, {f(c[1], nd)}]" if c else "--"


def tag(t):
    return t.replace("@", "@").replace("_", r"\_")


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    if name != "arms_lm.tex":  # wide tables are scaled to the text width
        body = body.replace(r"\begin{tabular}", r"\resizebox{\linewidth}{!}{\begin{tabular}").replace(
            r"\end{tabular}", r"\end{tabular}}")
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("% Generated by tables_results.py from results/analysis.json; do not edit by hand.\n" + body)


def confirmatory(a):
    t, s = a["confirmatory"]["tests"], a["secondary"]
    rows = []
    for k in ("H1-E", "H2-E", "H3-E"):
        r = t[k]
        rows.append(f"{k} & {tag(r['a'])} $-$ {tag(r['b'])} & {f(r['mean_diff'])} & {ci(r['ci95_two_level'])} & "
                    f"{f(r['mean_diff_ts'])} & {p(r['p_raw'])} & {p(r['p_holm'])} & {r['verdict']}\\\\")
    rows.append(r"\addlinespace")
    for k in ("H1-L", "H2-L", "H3-L"):
        r = t[k]
        rows.append(f"{k} & {tag(r['a'])} $-$ {tag(r['b'])} & {f(r['mean_diff'])} & {ci(r['ci95_signflip'])} & "
                    f"{f(r['mean_diff_best'])} & {p(r['p_final'])} & {p(r['p_holm'])} & {r['verdict']}\\\\")
    rows.append(r"\midrule")
    rows.append(r"\multicolumn{8}{l}{\emph{Secondary family F2 (separate Holm correction)}}\\")
    for k, lab in (("S-HBvsHU-E", "HB@0.10 $-$ HU@0.10 (E)"), ("S-RBvsRA-E", "RB@0.10 $-$ RA@0.10 (E)"),
                   ("S-HBvsHU-L", "HB@0.10 $-$ HU@0.10 (L)"), ("S-RBvsRA-L", "RB@0.10 $-$ RA@0.10 (L)"),
                   ("S-a", "S-HB@0.10 $-$ S-HU@0.10"), ("S-b", "S-HB@0.10 $-$ S-N")):
        r = s[k]
        enc = k.endswith("E") or k in ("S-a", "S-b")
        c = r.get("ci95_two_level") if enc else r.get("ci95_signflip")
        co = r.get("mean_diff_ts") if enc else r.get("mean_diff_best")
        pr = r.get("p_raw") if enc else r.get("p_final")
        rows.append(f"{k} & {lab} & {f(r['mean_diff'])} & {ci(c)} & {f(co)} & {p(pr)} & {p(r['p_holm_F2'])} & "
                    f"{r['verdict_F2']}\\\\")
    for k, lab in (("S-interaction-E", "(HB$-$HF)$-$(RB$-$RA) (E)"), ("S-EUG", "evidence-use gap, HB $-$ N"),
                   ("S-flip", "flip rate, HB $-$ N")):
        r = s[k]
        m = r.get("mean", r.get("mean_diff"))
        rows.append(f"{k} & {lab} & {f(m)} & -- & -- & {p(r['p'])} & {p(r['p_holm_F2'])} & "
                    f"{'Inconclusive' if r['p_holm_F2'] >= 0.05 else 'significant'}\\\\")
    body = r"""\begin{table}[t]
\centering
\caption{Confirmatory family F1 (Holm over six tests) and secondary family F2. Differences are first arm minus second
arm; lower is better, so a negative difference favours the first arm. Encoder (E): test Brier, 95\% two-level bootstrap CI, co-criterion =
temperature-scaled Brier difference. LM (L): final-step test NLL (nats/token), 95\% CI by inverting the sign-flip
test, co-criterion = test NLL at the best-validation step. $p$: exact two-sided sign-flip test over ten folds or seeds
(minimum 0.002). Student contrasts S-a and S-b use test Brier.}
\label{tab:confirmatory}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lllcccccl}
\toprule
ID & Contrast & Diff. & 95\% CI & Co-crit. & $p$ & $p_{\mathrm{Holm}}$ & Verdict\\
\midrule
""".replace("lllcccccl", "llcccccl") + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("confirmatory.tex", body)


def dtv(x):
    return "--" if x is None else f"{x:.3f}"


def arms_encoder(a):
    d = a["descriptive"]["S1"]
    order = ["N", "AD@0.20", "DK@0.05", "RA@0.05", "RA@0.10", "RB@0.10", "HU@0.05", "HU@0.10", "HF@0.10", "HB@0.10",
             "DB@0.10", "LS@0.2", "MX@0.9", "RDROP@0.5", "Q0", "L0"]
    rows = []
    for k in order:
        r = d[k]
        rows.append(f"{tag(k)} & {r['brier'][0]:.3f} ({r['brier'][1]:.3f}) & {r['brier_ts'][0]:.3f} & "
                    f"{100 * r['accuracy'][0]:.1f} & {r['macro_f1'][0]:.3f} & {r['auroc'][0]:.3f} & {r['ece15'][0]:.3f} & "
                    f"{f(100 * r['evidence_use_gap'], 1, sign=False)} & {100 * r['flip_rate']:.1f} & "
                    f"{dtv(r['realized_tv'])}\\\\")
    body = r"""\begin{table}[t]
\centering
\caption{PubMedQA test results by arm (BiomedBERT, ten folds; mean, with the between-fold SD of Brier in parentheses).
TS-Brier: Brier after temperature scaling fitted on each run's development fold. EUG: evidence-use gap (full minus
question-only accuracy, points). Flip: flip rate under a label-differing mismatched abstract (\%). $\bar D$: realized mean
displacement at the end of training. $\downarrow$: lower is better; $\uparrow$: higher is better. Q0 is trained on questions only and is scored here with the abstract; on its own
input format its accuracy is reported in the text. The majority-class accuracy is 55.2\%.}
\label{tab:arms_encoder}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lccccccccc}
\toprule
Arm & Brier$\downarrow$ & TS-Brier$\downarrow$ & Acc.\ (\%)$\uparrow$ & Macro-F1$\uparrow$ & AUROC$\uparrow$ & ECE$\downarrow$ & EUG & Flip & $\bar D$\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("arms_encoder.tex", body)


def arms_lm(a):
    import math
    d = a["descriptive"]["S2"]
    order = ["N", "AD@0.20", "DK@0.20", "RD@0.2", "RA@0.05", "RA@0.10", "RB@0.10", "HU@0.05", "HU@0.10", "HF@0.10",
             "HB@0.10", "HBsg@0.10", "DB@0.10"]
    rows = []
    for k in order:
        r = d[k]
        rows.append(f"{tag(k)} & {r['final'][0]:.4f} ({r['final'][1]:.4f}) & {r['best'][0]:.4f} ({r['best'][1]:.4f}) & "
                    f"{math.exp(r['final'][0]):.1f}\\\\")
    body = r"""\begin{table}[t]
\centering
\caption{Language-model test NLL by arm (nats/token; mean over ten seeds, between-seed SD in parentheses) at the final
step and at the best-validation step, and the corresponding perplexity ($\downarrow$: lower is better). HBsg is the extension-E8 arm (CapDrop with
$\alpha$ under stop-gradient); DB is budgeted DropKey (E3).}
\label{tab:arms_lm}
\footnotesize
\begin{tabular}{lccc}
\toprule
Arm & Final$\downarrow$ & Best-validation step$\downarrow$ & Perplexity (final)$\downarrow$\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("arms_lm.tex", body)


def extensions(a):
    e = a["extensions"]
    rows = []

    def enc(label, r, key="verdict_unadjusted"):
        rows.append(f"{label} & {tag(r['a'])} $-$ {tag(r['b'])} & {f(r['mean_diff'])} & {ci(r['ci95_two_level'])} & "
                    f"{f(r['mean_diff_ts'])} & {p(r['p_raw'])} & {r[key]}\\\\")

    def lm(label, r):
        rows.append(f"{label} & {tag(r['a'])} $-$ {tag(r['b'])} & {f(r['mean_diff'])} & {ci(r['ci90_t'])}$^\\dagger$ & "
                    f"{f(r['mean_diff_best'])} & {p(r['p_final'])} & {r['verdict']}\\\\")

    enc("P1 (seed 2)", e["P1_seed2_H1-E"])
    for k in ("H2-E folds 2-9", "H3-E folds 2-9"):
        enc(f"B6 OOF, {k.split()[0]}", e["B6_oof_replication"][k])
    enc("E-S3", e["ES3"]["S-H1"])
    enc("E-S3", e["ES3"]["S-KD"])
    for k in ("HB-HU", "HB@0.10-N", "HU@0.10-N", "AD@0.20-N"):
        enc("E5 BioLinkBERT", e["E5"][k])
    for k in ("HB-HU", "HB@0.10-N", "HU@0.10-N", "RA@0.05-N"):
        enc("E4 SciFact", e["E4"][k])
    enc("E1 R-Drop", e["E1"]["HB-RDROP*"])
    enc("E3 (encoder)", e["E3"]["S1 DB-HB"])
    lm("E3 (LM)", e["E3"]["S2 DB-HB"])
    lm("E8 (LM)", e["E8"])
    body = r"""\begin{table}[t]
\centering
\caption{Extension contrasts (descriptive; unadjusted $p$, verdicts by the H1 rules). Encoder rows: test Brier (E4:
SciFact development set used once as a test), 95\% two-level bootstrap CI, co-criterion = TS-Brier difference.
LM rows: final-step test NLL; $^\dagger$90\% paired-$t$ interval used for equivalence (margin $\pm0.010$);
co-criterion = best-validation-step difference. Differences are first arm minus second arm; lower is better, so a
negative difference favours the first arm. E2 (failure rates) is reported in the text; E6 was not run (budget).}
\label{tab:extensions}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lllcccl}
\toprule
Extension & Contrast & Diff. & CI & Co-crit. & $p$ & Verdict\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("extensions.tex", body)


if __name__ == "__main__":
    a = load(os.path.join(ROOT, "results", "analysis.json"))
    confirmatory(a)
    arms_encoder(a)
    arms_lm(a)
    extensions(a)
    print("tables written to", OUT)
